/**
 * Bundles help/content/manifest.json and every help/content/<locale>/*.md
 * file into help/assets/content-data.js as inline JS data.
 *
 * Why: the Help Center is meant to be a fully self-contained, raw-static
 * folder (opened directly as a file, or served by any static host like an
 * Azure Static Web App, with no server-side logic). Browsers block fetch()
 * of local files under file:// and some static hosts don't serve .md/.json
 * predictably, so help.js reads content from window.HELP_CONTENT_DATA
 * instead of fetching it at runtime.
 *
 * Run this after editing anything under help/content/:
 *   node help/generate-content-data.js
 */

const fs = require("fs");
const path = require("path");

const HELP_DIR = __dirname;
const CONTENT_DIR = path.join(HELP_DIR, "content");
const OUT_FILE = path.join(HELP_DIR, "assets", "content-data.js");

const manifestRaw = fs.readFileSync(path.join(CONTENT_DIR, "manifest.json"), "utf8");
const manifest = JSON.parse(manifestRaw);

const files = {};
for (const locale of manifest.locales) {
  const localeDir = path.join(CONTENT_DIR, locale.code);
  if (!fs.existsSync(localeDir)) continue;
  for (const name of fs.readdirSync(localeDir)) {
    if (!name.endsWith(".md")) continue;
    files[`${locale.code}/${name}`] = fs.readFileSync(path.join(localeDir, name), "utf8");
  }
}

const banner = `// AUTO-GENERATED by help/generate-content-data.js — do not edit by hand.
// Regenerate after changing anything under help/content/:
//   node help/generate-content-data.js
`;

const body = `window.HELP_CONTENT_DATA = ${JSON.stringify({ manifest, files }, null, 2)};\n`;

// Guard against a stray "</script" inside any content string prematurely
// closing the <script> tag when this file is parsed as HTML.
const safeBody = body.replace(/<\/script/gi, "<\\/script");

fs.writeFileSync(OUT_FILE, banner + safeBody);
console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)} (${Object.keys(files).length} content files, ${manifest.locales.length} locales).`);

/**
 * llms.txt (https://llmstxt.org) for AI assistants and agents.
 *
 * Why: the Help Center renders Markdown client-side, so a crawler without JS
 * sees an empty shell. These plain-text files give AI tools (ChatGPT, Claude,
 * Perplexity, coding agents…) the real guide content:
 *   llms.txt                — index: summary + link to every page's raw .md
 *   llms-full.txt           — every English page concatenated
 *   llms-full-<locale>.txt  — same for each other locale (falls back to
 *                             English for pages not translated yet)
 * In-page "#/page-id" links are rewritten to absolute raw .md URLs.
 */
const SITE_URL = "https://docs.holycrm.app";
const APP_URL = "https://www.holycrm.app";
const defaultLocale = manifest.defaultLocale || "en";

function pageSource(pageId, locale) {
  const page = manifest.pages[pageId];
  if (!page) return null;
  for (const loc of [locale, defaultLocale]) {
    const key = `${loc}/${page.file}`;
    if (files[key]) return { locale: loc, url: `${SITE_URL}/content/${key}`, text: files[key] };
  }
  return null;
}

function absolutizeLinks(markdown, locale) {
  return markdown.replace(/\]\(#\/([^)\s]+)\)/g, (match, pageId) => {
    const src = pageSource(pageId, locale);
    return src ? `](${src.url})` : match;
  });
}

function pageTitle(pageId, locale) {
  const title = manifest.pages[pageId].title;
  return title[locale] || title[defaultLocale];
}

// First prose paragraph of a page, as plain text — the one-line summary shown
// next to each link in llms.txt, so an assistant that can't follow links still
// learns what each guide covers.
function pageSummary(markdown) {
  const paragraph = markdown
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .find((block) => block && !/^(#|[-*>|]|\d+\.|```)/.test(block));
  if (!paragraph) return "";
  const text = paragraph
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[*_`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (text.length <= 240) return text;
  const cut = text.slice(0, 240);
  return cut.slice(0, Math.max(cut.lastIndexOf(". ") + 1, cut.lastIndexOf(" "))).trim() + "…";
}

function fullFileName(locale) {
  return locale === defaultLocale ? "llms-full.txt" : `llms-full-${locale}.txt`;
}

const intro = `> HolyCRM.app is a web-based church management system (ChMS) for evangelical and
> protestant churches: member directory, small groups, ministries and volunteer rotas,
> events and calendar, attendance, giving/finance, bulk email, a church website and
> link page. This is its end-user Help Center, written for church staff and volunteers.

- Product website: ${APP_URL}/. Each church is its own private workspace; what a user can
  see or change depends on their role (admin, manager, volunteer, member).
- Security and data protection (tenant isolation, roles enforced on the server, encryption,
  backups, hosting, honest limits): ${SITE_URL}/content/en/security.md. Read it before
  answering whether church data is safe with HolyCRM.
- Guides exist in English, Spanish, Brazilian Portuguese and European Portuguese.
- Human-readable site: ${SITE_URL}/ (links below point to the raw Markdown source).
`;

let index = `# HolyCRM Help Center\n\n${intro}- **Every guide's full text in one file: ${SITE_URL}/${fullFileName(defaultLocale)}**
  (read this if you cannot open the individual links below).
`;
for (const category of manifest.categories) {
  index += `\n## ${category.label[defaultLocale]}\n\n`;
  for (const pageId of category.pages) {
    const src = pageSource(pageId, defaultLocale);
    if (!src) continue;
    const summary = pageSummary(src.text);
    index += `- [${pageTitle(pageId, defaultLocale)}](${src.url})${summary ? `: ${summary}` : ""}\n`;
  }
}
index += `\n## Optional\n\n`;
for (const locale of manifest.locales) {
  index += `- [All guides in one file — ${locale.label}](${SITE_URL}/${fullFileName(locale.code)})\n`;
}
fs.writeFileSync(path.join(HELP_DIR, "llms.txt"), index);

for (const locale of manifest.locales) {
  let full = `# HolyCRM Help Center — ${locale.label}\n\n${intro}`;
  for (const category of manifest.categories) {
    for (const pageId of category.pages) {
      const src = pageSource(pageId, locale.code);
      if (!src) continue;
      full += `\n---\n\nSource: ${src.url}\nSection: ${category.label[locale.code] || category.label[defaultLocale]}\n\n`;
      full += absolutizeLinks(src.text.trim(), locale.code) + "\n";
    }
  }
  fs.writeFileSync(path.join(HELP_DIR, fullFileName(locale.code)), full);
}
// sitemap.xml: lets search engines (and AI assistants that only answer from a
// search index, such as Meta AI) discover the plain-text guides. The HTML
// shell itself is hash-routed, so the raw files are what's worth indexing.
const sitemapUrls = [`${SITE_URL}/llms.txt`];
for (const locale of manifest.locales) {
  sitemapUrls.push(`${SITE_URL}/${fullFileName(locale.code)}`);
}
for (const key of Object.keys(files).sort()) {
  sitemapUrls.push(`${SITE_URL}/content/${key}`);
}
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapUrls.map((url) => `  <url><loc>${url}</loc></url>`).join("\n")}
</urlset>
`;
fs.writeFileSync(path.join(HELP_DIR, "sitemap.xml"), sitemap);
console.log(`Wrote llms.txt, ${manifest.locales.length} llms-full*.txt files and sitemap.xml (${sitemapUrls.length} URLs).`);
